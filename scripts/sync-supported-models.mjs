import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = join(ROOT, "snippets/supported-models.mdx");
const PROVIDERS = {
  alibaba: "Alibaba",
  "black-forest-labs": "Black Forest Labs",
  bytedance: "ByteDance",
  elevenlabs: "ElevenLabs",
  google: "Google",
  "ideogram-ai": "Ideogram",
  kuaishou: "Kuaishou",
  lightricks: "Lightricks",
  luma: "Luma",
  meituan: "Meituan",
  microsoft: "Microsoft",
  minimax: "MiniMax",
  openai: "OpenAI",
  pika: "Pika",
  protoface: "Protoface",
  "pruna-ai": "Pruna",
  "recraft-ai": "Recraft",
  runway: "Runway",
  sync: "Sync",
  tencent: "Tencent",
  tripo3d: "Tripo",
  xai: "xAI",
};
const TYPES = {
  image: "Image",
  video: "Video",
  audio: "Audio",
  "model.3d": "3D",
};

function escapeText(value) {
  return String(value)
    .replace(
      /[&<>|{}]/g,
      (character) =>
        ({
          "&": "&amp;",
          "<": "&lt;",
          ">": "&gt;",
          "|": "&#124;",
          "{": "&#123;",
          "}": "&#125;",
        })[character],
    )
    .replace(/[\r\n]/g, " ");
}

export function renderSupportedModels(models, icons = new Set()) {
  const rows = [];
  const ids = new Set();
  for (const model of [...models].sort((a, b) =>
    String(a.id).localeCompare(String(b.id), "en"),
  )) {
    if (
      model.available !== true ||
      model.internal_only === true ||
      model.catalog_visible === false
    )
      continue;
    const operations = Object.keys(model.operations ?? {});
    if (
      !operations.length ||
      operations.some(
        (operation) =>
          !/^(image|video|audio|speech|music|3d)\./.test(operation),
      )
    )
      continue;
    if (
      !/^[a-z0-9-]+\/[a-z0-9._-]+$/.test(model.id) ||
      !model.display_name?.trim()
    ) {
      throw new Error("A public model is missing a valid ID or display name");
    }
    if (ids.has(model.id)) throw new Error(`Duplicate model ID: ${model.id}`);
    ids.add(model.id);
    const types = [...new Set(model.output_modalities)]
      .map((type) => {
        if (!TYPES[type]) throw new Error(`Unknown model output type: ${type}`);
        return TYPES[type];
      })
      .sort();
    if (!types.length) throw new Error(`No output type for ${model.id}`);
    const owner = model.id.split("/")[0];
    const provider =
      PROVIDERS[owner] ??
      owner
        .split("-")
        .map((word) => word[0].toUpperCase() + word.slice(1))
        .join(" ");
    const icon = icons.has(owner)
      ? `<img src="/images/providers/${owner}.png" alt="" width="20" height="20" className="inline-block rounded bg-white align-middle" /> `
      : "";
    rows.push(
      `| ${escapeText(model.display_name)}<br />\`${model.id}\` | ${icon}${escapeText(provider)} | ${types.join(", ")} |`,
    );
  }
  if (!rows.length)
    throw new Error(
      "No supported inference models; refusing to replace the table",
    );
  return [
    "{/* Generated by scripts/sync-supported-models.mjs. */}",
    "",
    "| Model | Provider | Type |",
    "| --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

async function main() {
  const args = process.argv.slice(2);
  const catalogIndex = args.indexOf("--catalog");
  let catalog;
  if (catalogIndex !== -1) {
    if (!args[catalogIndex + 1])
      throw new Error("--catalog requires a JSON file");
    catalog = JSON.parse(await readFile(args[catalogIndex + 1], "utf8"));
  } else {
    const key = process.env.PROTOFACE_API_KEY;
    if (!key)
      throw new Error("Set PROTOFACE_API_KEY or pass --catalog <file.json>");
    const response = await fetch("https://api.protoface.com/v1/models", {
      headers: { Authorization: `Bearer ${key}` },
      signal: AbortSignal.timeout(30_000),
    });
    if (!response.ok)
      throw new Error(`Model catalog returned HTTP ${response.status}`);
    catalog = await response.json();
  }
  if (!Array.isArray(catalog.data))
    throw new Error("Expected a /v1/models response with a data array");
  const icons = new Set(
    (await readdir(join(ROOT, "images/providers")))
      .filter((name) => name.endsWith(".png"))
      .map((name) => name.slice(0, -4)),
  );
  const content = renderSupportedModels(catalog.data, icons);
  if (args.includes("--check")) {
    if ((await readFile(OUTPUT, "utf8")) !== content)
      throw new Error("Supported models table is out of date");
    console.log("Supported models table is up to date");
  } else {
    await writeFile(OUTPUT, content);
    console.log("Updated snippets/supported-models.mdx");
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
